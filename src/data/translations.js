/**
 * Safe translation helper function.
 * Resolves nested paths like 'nav.home' to translated string.
 */
export function getTranslation(key, lang = 'es') {
  const currentLang = translations[lang] || translations['es']
  const keys = key.split('.')
  let result = currentLang

  for (const k of keys) {
    if (result && result[k] !== undefined) {
      result = result[k]
    } else {
      // Fallback to Spanish
      let fallbackResult = translations['es']
      for (const fk of keys) {
        if (fallbackResult && fallbackResult[fk] !== undefined) {
          fallbackResult = fallbackResult[fk]
        } else {
          return key // Return key itself if fallback fails
        }
      }
      return fallbackResult
    }
  }

  return result
}
